#!/usr/bin/env python3
"""Refresh the bundled CCFDDL snapshot used when the network is unavailable."""

from __future__ import annotations

import datetime as dt
import json
import pathlib
import urllib.request

URL = "https://ccfddl.com/conference/initial.json"
ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "package" / "contents" / "data" / "snapshot.js"


def main() -> None:
    request = urllib.request.Request(
        URL,
        headers={
            "User-Agent": "ccfddl-plasmoid/1.0 (+https://ccfddl.com/)",
            "Accept": "application/json",
        },
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        payload = json.load(response)

    conferences = payload["conferences"] if isinstance(payload, dict) else payload
    if not isinstance(conferences, list) or not conferences:
        raise SystemExit("ccfddl returned no conferences")

    today = dt.date.today().isoformat()
    body = json.dumps(conferences, ensure_ascii=False, separators=(",", ":"))
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(
        ".pragma library\n"
        "// Generated by tools/update-data.py. Do not edit by hand.\n"
        f'var CCFDDL_SNAPSHOT_DATE = "{today}";\n'
        f"var CCFDDL_CONFERENCES = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {TARGET} ({TARGET.stat().st_size:,} bytes, {len(conferences)} conferences, {today})")


if __name__ == "__main__":
    main()
